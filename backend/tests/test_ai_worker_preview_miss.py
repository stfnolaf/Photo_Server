"""Phase 3 of the preview cache eviction plan: AI-worker resilience under miss.

Previews are disposable: the LRU evictor (Phase 2) or a wiped cache volume can
remove a set that Postgres still records as ``ready``. The AI pipeline must
therefore regenerate its own preview on a cache miss instead of hard-failing,
and a reuse candidate whose preview is no longer cached must simply be skipped
(degrading to a full analysis) rather than fail the job.

The VLM, the Ollama digest lookup, and the face detector are stubbed (no
Ollama or AI-worker service is started); the miss paths run real
``worker.generate()`` / fingerprint / candidate / publish code against a
disposable Postgres catalog, S3 bucket, and scratch directory. One further
test (Phase 2B) drives the real ``RemoteFaceAnalyzer`` against an in-process
stub HTTP server implementing the face-service contract — still without any
external service.

Phase 3A adds the service gate to every test here: both service URLs are
stub-configured and both probes stubbed healthy, so the worker claims
exactly as before. The gate's own behavior (unconfigured idle, probe-blocked
claims, requeue on a mid-job outage, the bounded dispatcher) is covered by
the ``test_unconfigured_*`` / ``test_gate_*`` / ``test_face_outage_*`` /
``test_vlm_request_error_*`` / ``test_dispatcher_*`` tests at the end of the
file, using the stub HTTP server and no external service.
"""

